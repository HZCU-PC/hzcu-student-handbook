def main():
    source = PAGE.read_text(encoding="utf-8")
    match = PATTERN.search(source)
    if not match:
        raise SystemExit("papers-json block not found")
    papers = json.loads(match.group(2))
    by_id = {p["id"]: p for p in papers}
    expected = set(CONTENT)
    if expected != set("WB-A44 WB-A54 WB-A55 WB-B19 WB-B24 WB-B25 WB-B26 WB-B27 WB-B28 WB-B29 WB-B30 WB-B31 WB-C11 WB-C14 WB-E05 WB-E06 WB-E07 WB-D10".split()):
        raise SystemExit("CONTENT ids differ from DISPATCH")
    missing = sorted(expected - set(by_id))
    if missing:
        raise SystemExit(f"Unknown paper ids: {missing}")
    stale = sorted(pid for pid in expected if "核心问题，是如何" not in by_id[pid].get("solve", ""))
    if stale:
        raise SystemExit(f"Refusing to overwrite non-template solve entries: {stale}")
    for pid, fields in CONTENT.items():
        by_id[pid].update(fields)
    payload = json.dumps(papers, ensure_ascii=False, separators=(",", ":"))
    PAGE.write_text(source[:match.start(2)] + payload + source[match.end(2):], encoding="utf-8")
    print(f"batch06 CDX applied: {len(CONTENT)} JSON patches")


if __name__ == "__main__":
    main()
